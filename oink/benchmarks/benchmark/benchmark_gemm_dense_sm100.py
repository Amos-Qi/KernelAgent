"""Correctness-gated SM100/SM103 benchmark for Oink dense GEMM.

generated by KernelAgent-Oink(https://github.com/meta-pytorch/KernelAgent)
"""

from __future__ import annotations

import argparse
import math
import os
from typing import Any

import torch

os.environ.setdefault("PYTORCH_ALLOC_CONF", "expandable_segments:True")

from bench_utils import (  # noqa: E402
    collect_device_meta,
    do_bench_triton,
    ensure_blackwell_arch_env,
    ensure_oink_src_on_path,
    write_json,
)

ensure_blackwell_arch_env()
ensure_oink_src_on_path()

from kernelagent_oink.blackwell import gemm_dense as oink_gemm  # noqa: E402


def _parse_shape(shape: str) -> tuple[int, int, int]:
    parts = shape.lower().split("x")
    if len(parts) != 3:
        raise argparse.ArgumentTypeError("shape must be MxNxK")
    return tuple(int(x) for x in parts)  # type: ignore[return-value]


def _bytes(m: int, n: int, k: int) -> int:
    elem = torch.tensor(0, dtype=torch.bfloat16).element_size()
    return int((m * k + k * n + m * n) * elem)


def bench_shape(shape: tuple[int, int, int], args: argparse.Namespace) -> dict[str, Any]:
    m, n, k = shape
    torch.manual_seed(args.seed)
    a = torch.randn(m, k, device="cuda", dtype=torch.bfloat16)
    b = torch.randn(k, n, device="cuda", dtype=torch.bfloat16)

    ref = (a.float() @ b.float()).to(torch.bfloat16)
    out = torch.ops.oink.gemm(a, b, torch.bfloat16)
    torch.testing.assert_close(out, ref, atol=1e-2, rtol=1e-2)

    def fn_oink():
        return torch.ops.oink.gemm(a, b, torch.bfloat16)

    def fn_ref():
        return torch.mm(a, b)

    ms_oink = do_bench_triton(fn_oink, warmup_ms=args.warmup_ms, rep_ms=args.iters)
    ms_ref = do_bench_triton(fn_ref, warmup_ms=args.warmup_ms, rep_ms=args.iters)
    flops = int(2 * m * n * k)
    useful_bytes = _bytes(m, n, k)
    return {
        "M": int(m),
        "N": int(n),
        "K": int(k),
        "oink_ms": float(ms_oink),
        "torch_ms": float(ms_ref),
        "oink_over_torch_x": float(ms_ref / ms_oink) if ms_oink > 0 else math.nan,
        "flops": flops,
        "useful_bytes": useful_bytes,
        "oink_tflops": float(flops / (ms_oink * 1e-3) / 1e12),
        "torch_tflops": float(flops / (ms_ref * 1e-3) / 1e12),
        "oink_gbps": float(useful_bytes / (ms_oink * 1e-3) / 1e9),
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--shapes", type=str, default="128x128x128")
    parser.add_argument("--warmup-ms", type=int, default=25)
    parser.add_argument("--iters", type=int, default=100)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--json", type=str, default=None)
    args = parser.parse_args()

    if not torch.cuda.is_available():
        raise SystemExit("CUDA not available")
    torch.cuda.set_device(0)
    import kernelagent_oink

    kernelagent_oink.register(force=True)
    rows = [bench_shape(_parse_shape(s.strip()), args) for s in args.shapes.split(",") if s.strip()]
    for row in rows:
        print(
            f"M={row['M']} N={row['N']} K={row['K']} "
            f"oink {row['oink_ms']:.4f} ms {row['oink_tflops']:.2f} TFLOP/s "
            f"torch {row['torch_ms']:.4f} ms {row['torch_tflops']:.2f} TFLOP/s "
            f"speedup {row['oink_over_torch_x']:.3f}x useful {row['oink_gbps']:.1f} GB/s"
        )
    if args.json:
        write_json(args.json, collect_device_meta(), rows)


if __name__ == "__main__":
    main()
