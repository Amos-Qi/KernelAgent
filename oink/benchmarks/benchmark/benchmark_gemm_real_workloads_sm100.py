Shape = tuple[str, str, int, int, int]

QUACK_TRANSFORMER_SHAPES: list[Shape] = [
    # Follows references/cute_kernels/quack/benchmarks/benchmark_gemm_autotuned.py
    # for batch=8192, dim=4096, ffn=int(3.5*dim)=14336, qkv_dim=6144.
    ("quack_transformer", "qkv_proj", 8192, 6144, 4096),
    ("quack_transformer", "attn_out", 8192, 4096, 4096),
    ("quack_transformer", "ffn_down", 8192, 4096, 14336),
    ("quack_transformer", "ffn_up_gate_dense_unfused", 8192, 28672, 4096),
]

DSV3_SHAPES: list[Shape] = [
    # DeepSeek-V3-like dense projection / MLA low-rank shapes.
    # hidden=7168, q_lora_rank=1536, kv_lora_rank=512, qk_rope=64,
    # q_out=128*(128+64)=24576, kv_out=128*(128+128)=32768.
    ("deepseek_v3", "hidden_proj", 4096, 7168, 7168),
    ("deepseek_v3", "q_lora_a", 4096, 1536, 7168),
    ("deepseek_v3", "q_lora_b", 4096, 24576, 1536),
    ("deepseek_v3", "kv_lora_a", 4096, 576, 7168),
    ("deepseek_v3", "kv_lora_b", 4096, 32768, 512),
]

DSV4_SHAPES: list[Shape] = [
    # DeepSeek-V4-Flash-like dense projection shapes. Use larger M to represent
    # heavier prefill pressure while keeping the same hidden / low-rank widths.
    ("deepseek_v4_flash", "hidden_proj", 8192, 7168, 7168),
    ("deepseek_v4_flash", "q_lora_a", 8192, 1536, 7168),
    ("deepseek_v4_flash", "q_lora_b", 8192, 24576, 1536),
]

SHAPE_SUITES: dict[str, list[Shape]] = {
    "quack_transformer": QUACK_TRANSFORMER_SHAPES,
    "dsv3": DSV3_SHAPES,
    "dsv4": DSV4_SHAPES,
    "all": QUACK_TRANSFORMER_SHAPES + DSV3_SHAPES + DSV4_SHAPES,
}
SHAPE_BY_NAME: dict[str, Shape] = {name: row for rows in SHAPE_SUITES.values() for row in rows for name in [row[1]]}


def _parse_pair(text: str) -> tuple[int, int]:
    parts = text.lower().replace("x", ",").split(",")
    if len(parts) != 2:
        raise argparse.ArgumentTypeError(f"expected two integers, got {text!r}")
    return int(parts[0]), int(parts[1])


def _parse_bool(text: str) -> bool:
    val = str(text).strip().lower()
    if val in {"1", "true", "yes", "on"}:
        return True
    if val in {"0", "false", "no", "off"}:
        return False
    raise argparse.ArgumentTypeError(f"expected boolean, got {text!r}")


def _dtype(name: str) -> torch.dtype:
    if name in {"bf16", "bfloat16"}:
        return torch.bfloat16
    if name in {"fp16", "float16", "half"}:
        return torch.float16
    raise argparse.ArgumentTypeError("this benchmark currently supports bf16/fp16 inputs")


def _try_import_quack():
    try:
        from quack.gemm_interface import gemm as quack_gemm
        from quack.gemm_interface import gemm_out as quack_gemm_out

        return quack_gemm, quack_gemm_out, None
    except Exception as exc:  # pragma: no cover - depends on optional local checkout
        return None, None, exc


def _shape_rows(args: argparse.Namespace) -> list[Shape]:
    if args.suite == "single":
        if args.shape not in SHAPE_BY_NAME:
            raise ValueError(f"unknown --shape {args.shape!r}; choices={sorted(SHAPE_BY_NAME)}")
        return [SHAPE_BY_NAME[args.shape]]
    return SHAPE_SUITES[args.suite]


def _flops(m: int, n: int, k: int) -> int:
    return int(2 * m * n * k)


def _useful_bytes(m: int, n: int, k: int, dtype: torch.dtype) -> int:
    elem = torch.empty((), dtype=dtype).element_size()
    return int((m * k + k * n + m * n) * elem)


def _tflops(ms: float, m: int, n: int, k: int) -> float:
    return float(_flops(m, n, k) / (ms * 1e-3) / 1e12) if ms > 0 else math.nan


def _gbps(ms: float, m: int, n: int, k: int, dtype: torch.dtype) -> float:
    return float(_useful_bytes(m, n, k, dtype) / (ms * 1e-3) / 1e9) if ms > 0 else math.nan


def _arithmetic_intensity(m: int, n: int, k: int, dtype: torch.dtype) -> float:
    return float(_flops(m, n, k) / _useful_bytes(m, n, k, dtype))


def _close_stats(x: torch.Tensor, ref: torch.Tensor, k: int) -> dict[str, float]:
    diff = (x - ref).abs()
    # BF16 matmul accumulates enough rounding variation at large K that an absolute
    # tolerance of 4-8 is more meaningful than the tiny unit-test tolerance.
    return {
        "max_abs": float(diff.max().item()),
        "mean_abs": float(diff.float().mean().item()),
        "atol_used": float(8.0 if k >= 8192 else 4.0),
        "rtol_used": 1e-2,
    }


def _make_oink_fn(
    a: torch.Tensor,
    b: torch.Tensor,
    out: torch.Tensor,
    args: argparse.Namespace,
) -> Callable[[], torch.Tensor]:
    if args.oink_mode == "public":
        return lambda: torch.ops.oink.gemm(a, b, args.dtype)
    if args.oink_mode == "public-out":
        def public_out_fn() -> torch.Tensor:
            torch.ops.oink.gemm_out(a, b, out)
            return out

        return public_out_fn
    tile = args.oink_tile
    cluster = args.oink_cluster
    use_2cta = bool(args.oink_2cta)
    use_tma_store = bool(args.oink_tma_store)

    def fn() -> torch.Tensor:
        return oink_gemm.gemm_backend_out(
            a,
            b,
            out,
            mma_tiler_mn=tile,
            cluster_shape_mn=cluster,
            use_2cta_instrs=use_2cta,
            use_tma_store=use_tma_store,
            max_active_clusters=args.oink_max_active_clusters,
            scheduler_swizzle_size=args.oink_scheduler_swizzle_size,
            scheduler_raster_along_m=args.oink_scheduler_raster_along_m,
            use_dynamic_scheduler=args.oink_dynamic_scheduler,
            swap_ab=args.oink_swap_ab,
            dynamic_warp_layout=args.oink_dynamic_warp_layout,
            prefetch_dist=args.oink_prefetch_dist,
        )

    return fn


def _make_quack_fn(
    a: torch.Tensor,
    b: torch.Tensor,
    out: torch.Tensor,
    args: argparse.Namespace,
    quack_gemm,
    quack_gemm_out,
) -> Callable[[], torch.Tensor] | None:
    if quack_gemm is None:
        return None
    if args.quack_mode == "public-out":
        def quack_out_fn() -> torch.Tensor:
            quack_gemm_out(a, b, out, tuned=not args.quack_untuned)
            return out

        return quack_out_fn
    return lambda: quack_gemm(a, b, out_dtype=args.dtype, tuned=not args.quack_untuned)


def _bench_optional(label: str, fn: Callable[[], torch.Tensor] | None, args: argparse.Namespace) -> tuple[float | None, str | None]:
    if fn is None:
        return None, f"{label} unavailable"
    try:
        return float(do_bench_triton(fn, warmup_ms=args.warmup_ms, rep_ms=args.iters)), None
    except Exception as exc:
        return None, f"{label} failed: {type(exc).__name__}: {exc}"


def bench_shape(row: Shape, args: argparse.Namespace, quack_gemm, quack_gemm_out) -> dict[str, Any]:
    suite, name, m, n, k = row
    print(f"\n[{suite}] {name}: M={m} N={n} K={k}", flush=True)
    torch.manual_seed(abs(hash((suite, name, m, n, k, int(args.seed)))) % (2**31))
    a = torch.randn(m, k, device="cuda", dtype=args.dtype)
    b = torch.randn(k, n, device="cuda", dtype=args.dtype)
    out_oink = torch.empty((m, n), device="cuda", dtype=args.dtype)
    out_quack = torch.empty((m, n), device="cuda", dtype=args.dtype)

    ref = (a.float() @ b.float()).to(args.dtype)
    oink_fn = _make_oink_fn(a, b, out_oink, args)
    out_o = oink_fn()
    err_o = _close_stats(out_o, ref, k)
    torch.testing.assert_close(out_o, ref, atol=err_o["atol_used"], rtol=err_o["rtol_used"])

    err_q = None
    quack_fn = _make_quack_fn(a, b, out_quack, args, quack_gemm, quack_gemm_out)
    if quack_fn is not None and args.provider in {"all", "quack"}:
        out_q = quack_fn()
        err_q = _close_stats(out_q, ref, k)
        torch.testing.assert_close(out_q, ref, atol=err_q["atol_used"], rtol=err_q["rtol_used"])
    torch.cuda.synchronize()

    ms_o, err_o_bench = _bench_optional("oink", oink_fn if args.provider in {"all", "oink"} else None, args)
    ms_q, err_q_bench = _bench_optional(
        "quack",
        quack_fn if quack_fn is not None and args.provider in {"all", "quack"} else None,
        args,
    )
    ms_t, err_t_bench = _bench_optional("torch", (lambda: torch.mm(a, b)) if args.provider in {"all", "torch"} else None, args)

    result: dict[str, Any] = {
        "suite": suite,
        "name": name,
        "M": int(m),
        "N": int(n),
        "K": int(k),
        "dtype": str(args.dtype).replace("torch.", ""),
        "oink_mode": args.oink_mode,
        "oink_tile": list(args.oink_tile),
        "oink_cluster": list(args.oink_cluster),
        "oink_2cta": bool(args.oink_2cta),
        "oink_tma_store": bool(args.oink_tma_store),
        "oink_max_active_clusters": args.oink_max_active_clusters,
        "oink_scheduler_swizzle_size": args.oink_scheduler_swizzle_size,
        "oink_scheduler_raster_along_m": bool(args.oink_scheduler_raster_along_m),
        "oink_dynamic_scheduler": bool(args.oink_dynamic_scheduler),
        "oink_swap_ab": bool(args.oink_swap_ab),
        "oink_dynamic_warp_layout": args.oink_dynamic_warp_layout,
        "oink_prefetch_dist": args.oink_prefetch_dist,
        "quack_mode": args.quack_mode,
        "quack_tuned": not args.quack_untuned,
        "flops": _flops(m, n, k),
        "useful_bytes": _useful_bytes(m, n, k, args.dtype),
        "arithmetic_intensity_flop_per_byte": _arithmetic_intensity(m, n, k, args.dtype),
        "oink_ms": ms_o,
        "quack_ms": ms_q,
        "torch_ms": ms_t,
        "oink_error": err_o,
        "quack_error": err_q,
        "errors": [e for e in (err_o_bench, err_q_bench, err_t_bench) if e is not None],
    }
    for provider, ms in (("oink", ms_o), ("quack", ms_q), ("torch", ms_t)):
        result[f"{provider}_tflops"] = _tflops(ms, m, n, k) if ms is not None else None
        result[f"{provider}_gbps_useful"] = _gbps(ms, m, n, k, args.dtype) if ms is not None else None
        if args.peak_tflops and result[f"{provider}_tflops"] is not None:
            result[f"{provider}_pct_peak"] = float(result[f"{provider}_tflops"] / args.peak_tflops * 100.0)
    if ms_o is not None and ms_q is not None:
        result["oink_over_quack_x"] = float(ms_q / ms_o)
        result["target_oink_ms_for_1p2x_quack"] = float(ms_q / 1.2)
        result["target_1p2x_quack_tflops"] = float(_tflops(ms_q / 1.2, m, n, k))
        if args.peak_tflops:
            result["target_1p2x_quack_pct_peak"] = float(result["target_1p2x_quack_tflops"] / args.peak_tflops * 100.0)
    if ms_o is not None and ms_t is not None:
        result["oink_over_torch_x"] = float(ms_t / ms_o)

    print(
        f"  Oink {ms_o if ms_o is not None else math.nan:.4f} ms "
        f"{result['oink_tflops'] if result['oink_tflops'] is not None else math.nan:.1f} TF/s | "
        f"Quack {ms_q if ms_q is not None else math.nan:.4f} ms "
        f"{result['quack_tflops'] if result['quack_tflops'] is not None else math.nan:.1f} TF/s | "
        f"torch {ms_t if ms_t is not None else math.nan:.4f} ms "
        f"{result['torch_tflops'] if result['torch_tflops'] is not None else math.nan:.1f} TF/s | "
        f"Oink/Quack {result.get('oink_over_quack_x', math.nan):.3f}x",
        flush=True,
    )
    return result


def _geomean(values: list[float]) -> float:
    vals = [x for x in values if x > 0 and math.isfinite(x)]
    if not vals:
        return math.nan
    return float(math.exp(sum(math.log(x) for x in vals) / len(vals)))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--suite", choices=["all", "quack_transformer", "dsv3", "dsv4", "single"], default="all")
    parser.add_argument("--shape", choices=sorted(SHAPE_BY_NAME), default="qkv_proj")
    parser.add_argument("--provider", choices=["all", "oink", "quack", "torch"], default="all")
    parser.add_argument("--dtype", type=_dtype, default=torch.bfloat16)
    parser.add_argument("--iters", type=int, default=20)
    parser.add_argument("--warmup-ms", type=int, default=5)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--json", type=str, default=None)
    parser.add_argument("--peak-tflops", type=float, default=None)
    parser.add_argument("--oink-mode", choices=["public", "public-out", "backend-out"], default="public")
    parser.add_argument("--oink-tile", type=_parse_pair, default=(256, 128))
    parser.add_argument("--oink-cluster", type=_parse_pair, default=(2, 1))
    parser.add_argument("--oink-2cta", type=_parse_bool, default=True)
    parser.add_argument("--oink-tma-store", type=_parse_bool, default=True)
    parser.add_argument("--oink-max-active-clusters", type=int, default=None)
    parser.add_argument("--oink-scheduler-swizzle-size", type=int, default=1)
    parser.add_argument("--oink-scheduler-raster-along-m", type=_parse_bool, default=True)
    parser.add_argument("--oink-dynamic-scheduler", type=_parse_bool, default=False)
    parser.add_argument("--oink-swap-ab", type=_parse_bool, default=False)
    parser.add_argument("--oink-dynamic-warp-layout", choices=["quack8", "cutlass7"], default="quack8")
    parser.add_argument("--oink-prefetch-dist", type=int, default=0)
    parser.add_argument("--quack-mode", choices=["public", "public-out"], default="public")
    parser.add_argument("--quack-untuned", action="store_true")
    args = parser.parse_args()

    if not torch.cuda.is_available():
        raise SystemExit("CUDA not available")
    torch.cuda.set_device(0)
    import kernelagent_oink

    kernelagent_oink.register(force=True)
    quack_gemm, quack_gemm_out, quack_error = _try_import_quack()
    if quack_error is not None and args.provider in {"all", "quack"}:
        raise RuntimeError(
            "Quack baseline unavailable. Add local Quack checkout to PYTHONPATH, e.g. "
            "PYTHONPATH=references/cute_kernels/quack:oink/src"
        ) from quack_error

    rows = [bench_shape(row, args, quack_gemm, quack_gemm_out) for row in _shape_rows(args)]
    speeds = [row["oink_over_quack_x"] for row in rows if row.get("oink_over_quack_x") is not None]
    summary = {
        "geomean_oink_over_quack_x": _geomean(speeds),
        "num_speedup_rows": len(speeds),
        "target_geomean_oink_over_quack_x": 1.2,
    }
    print("\nSUMMARY", json.dumps(summary, indent=2), flush=True)
    if args.json:
        write_json(args.json, collect_device_meta(), rows, extra=summary)


if __name__ == "__main__":
    main()
