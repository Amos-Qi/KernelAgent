ensure_blackwell_arch_env()
ensure_oink_src_on_path()

from kernelagent_oink.blackwell import moe_grouped_gemm as oink_moe  # noqa: E402


_TOL = dict(atol=1e-2, rtol=1e-2)


def _make_offsets(total_tokens: int, experts: int, distribution: str) -> torch.Tensor:
    if distribution == "equal":
        base = total_tokens // experts
        rem = total_tokens % experts
        sizes = [base + (1 if i < rem else 0) for i in range(experts)]
    elif distribution == "skewed":
        weights = torch.arange(1, experts + 1, dtype=torch.float64)
        sizes_t = torch.floor(weights / weights.sum() * total_tokens).to(torch.int64)
        while int(sizes_t.sum().item()) < total_tokens:
            sizes_t[-1] += 1
        sizes = [int(x) for x in sizes_t.tolist()]
    else:
        raise ValueError(f"unknown distribution: {distribution}")
    offs = []
    running = 0
    for size in sizes:
        running += int(size)
        offs.append(running)
    return torch.tensor(offs, device="cuda", dtype=torch.int32)


def _manual_ref(a: torch.Tensor, b: torch.Tensor, offs: torch.Tensor, scenario: str) -> torch.Tensor:
    return oink_moe.grouped_mm_ref(a, b, offs, scenario=scenario, out_dtype=a.dtype)


def _problem_tensors(
    *,
    scenario: str,
    tokens: int,
    experts: int,
    hidden: int,
    intermediate: int,
    distribution: str,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    offs = _make_offsets(tokens, experts, distribution)
    if scenario == "2Dx3D":
        mat_a = torch.randn(tokens, hidden, device="cuda", dtype=torch.bfloat16)
        mat_b = torch.randn(experts, hidden, intermediate, device="cuda", dtype=torch.bfloat16)
    elif scenario == "2Dx2D":
        mat_a = torch.randn(hidden, tokens, device="cuda", dtype=torch.bfloat16)
        mat_b = torch.randn(tokens, intermediate, device="cuda", dtype=torch.bfloat16)
    else:
        raise ValueError(f"unsupported scenario: {scenario}")
    return mat_a, mat_b, offs


def _flops(*, scenario: str, offs: torch.Tensor, hidden: int, intermediate: int) -> int:
    sizes = torch.diff(torch.cat([torch.zeros(1, device=offs.device, dtype=offs.dtype), offs])).cpu()
    if scenario == "2Dx3D":
        return int(sum(2 * int(m) * hidden * intermediate for m in sizes))
    return int(sum(2 * hidden * int(k) * intermediate for k in sizes))


def _bytes(*, scenario: str, tokens: int, experts: int, hidden: int, intermediate: int) -> int:
    elem = torch.tensor(0, dtype=torch.bfloat16).element_size()
    if scenario == "2Dx3D":
        return int((tokens * hidden + experts * hidden * intermediate + tokens * intermediate) * elem)
    return int((hidden * tokens + tokens * intermediate + experts * hidden * intermediate) * elem)


def bench_one(args: argparse.Namespace) -> dict[str, Any]:
    torch.manual_seed(args.seed)
    mat_a, mat_b, offs = _problem_tensors(
        scenario=args.scenario,
        tokens=args.tokens,
        experts=args.experts,
        hidden=args.hidden,
        intermediate=args.intermediate,
        distribution=args.distribution,
    )

    ref = _manual_ref(mat_a, mat_b, offs, args.scenario)
    out = torch.ops.oink.grouped_mm(mat_a, mat_b, offs, args.scenario, torch.bfloat16)
    torch.testing.assert_close(out, ref, **_TOL)

    backend = "oink"
    if not oink_moe._cutlass_dsl_supports_moe_tensormap():  # type: ignore[attr-defined]
        backend = "torch_or_reference_fallback"

    def fn_oink():
        return torch.ops.oink.grouped_mm(mat_a, mat_b, offs, args.scenario, torch.bfloat16)

    def fn_ref():
        return _manual_ref(mat_a, mat_b, offs, args.scenario)

    ms_oink = do_bench_triton(fn_oink, warmup_ms=args.warmup_ms, rep_ms=args.iters)
    ms_ref = do_bench_triton(fn_ref, warmup_ms=args.warmup_ms, rep_ms=args.iters)
    flops = _flops(
        scenario=args.scenario,
        offs=offs,
        hidden=args.hidden,
        intermediate=args.intermediate,
    )
    useful_bytes = _bytes(
        scenario=args.scenario,
        tokens=args.tokens,
        experts=args.experts,
        hidden=args.hidden,
        intermediate=args.intermediate,
    )
    return {
        "scenario": args.scenario,
        "backend": backend,
        "experts": int(args.experts),
        "tokens": int(args.tokens),
        "hidden": int(args.hidden),
        "intermediate": int(args.intermediate),
        "distribution": args.distribution,
        "oink_ms": float(ms_oink),
        "ref_ms": float(ms_ref),
        "oink_over_ref_x": float(ms_ref / ms_oink) if ms_oink > 0 else math.nan,
        "flops": int(flops),
        "useful_bytes": int(useful_bytes),
        "oink_tflops": float(flops / (ms_oink * 1e-3) / 1e12),
        "oink_gbps": float(useful_bytes / (ms_oink * 1e-3) / 1e9),
        "cutlass_dsl_version": oink_moe._cutlass_dsl_version(),  # type: ignore[attr-defined]
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--scenario", choices=["2Dx3D", "2Dx2D"], default="2Dx3D")
    parser.add_argument("--tokens", type=int, default=1024)
    parser.add_argument("--experts", type=int, default=8)
    parser.add_argument("--hidden", type=int, default=4096)
    parser.add_argument("--intermediate", type=int, default=4096)
    parser.add_argument("--distribution", choices=["equal", "skewed"], default="equal")
    parser.add_argument("--warmup-ms", type=int, default=25)
    parser.add_argument("--iters", type=int, default=100)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--json", type=str, default=None)
    args = parser.parse_args()

    if not torch.cuda.is_available():
        raise SystemExit("CUDA not available")
    torch.cuda.set_device(0)
    import kernelagent_oink

    kernelagent_oink.register(force=True)
    row = bench_one(args)
    print(
        f"{row['scenario']} {row['backend']} tokens={row['tokens']} experts={row['experts']} "
        f"hidden={row['hidden']} intermediate={row['intermediate']} "
        f"oink {row['oink_ms']:.4f} ms {row['oink_tflops']:.2f} TFLOP/s "
        f"useful {row['oink_gbps']:.1f} GB/s ref {row['ref_ms']:.4f} ms "
        f"speedup {row['oink_over_ref_x']:.3f}x"
    )
    if args.json:
        write_json(args.json, collect_device_meta(), [row])


if __name__ == "__main__":
    main()
