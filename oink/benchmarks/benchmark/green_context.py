"""CUDA green-context helpers for local Oink Rubin approximation benchmarks.

generated by KernelAgent-Oink(https://github.com/meta-pytorch/KernelAgent)

The CUDA 13.1 green-context APIs let benchmark code create a stream backed by
a subset of a GPU's SM resources.  Oink kernels already launch on PyTorch's
current stream, so benchmarks can run inside ``torch.cuda.stream(ctx.stream)``
to restrict their launches to the green context.

This is benchmark-only infrastructure: it does not change production Oink
dispatch, allocation behavior, or the device-reported SM count.
"""

from __future__ import annotations

import atexit
from dataclasses import dataclass
from typing import Any, Dict, Optional

import torch

try:
    import cuda.bindings.driver as cuda
except Exception:  # pragma: no cover - handled at runtime by create_green_context
    cuda = None  # type: ignore[assignment]


def _cuda_success() -> object:
    assert cuda is not None
    return cuda.CUresult.CUDA_SUCCESS


def _check_cuda(ret, what: str):
    """Return cuda-python payload or raise a readable RuntimeError."""
    if not isinstance(ret, tuple) or not ret:
        raise RuntimeError(f"{what} returned unexpected cuda-python result: {ret!r}")
    err = ret[0]
    if err != _cuda_success():
        raise RuntimeError(f"{what} failed: {err!s}")
    if len(ret) == 1:
        return ()
    if len(ret) == 2:
        return ret[1]
    return ret[1:]


@dataclass
class GreenContext:
    """Keep a green context and its stream alive for benchmark lifetime."""

    requested_sms: int
    actual_sms: int
    device_index: int
    full_device_sms: int
    min_sm_partition_size: int
    sm_coscheduled_alignment: int
    _green_ctx: Any
    _cu_stream: Any
    stream: torch.cuda.ExternalStream
    _destroyed: bool = False

    @property
    def stream_handle(self) -> int:
        return int(self._cu_stream)

    def torch_stream(self):
        return torch.cuda.stream(self.stream)

    def synchronize(self) -> None:
        if cuda is not None and not self._destroyed:
            _check_cuda(cuda.cuStreamSynchronize(self._cu_stream), "cuStreamSynchronize")

    def close(self) -> None:
        if cuda is None or self._destroyed:
            return
        # Synchronize before destroying to keep teardown deterministic.
        _check_cuda(cuda.cuStreamSynchronize(self._cu_stream), "cuStreamSynchronize")
        _check_cuda(cuda.cuStreamDestroy(self._cu_stream), "cuStreamDestroy")
        _check_cuda(cuda.cuGreenCtxDestroy(self._green_ctx), "cuGreenCtxDestroy")
        self._destroyed = True

    def metadata(self) -> Dict[str, Any]:
        return {
            "green_context_requested_sms": int(self.requested_sms),
            "green_context_actual_sms": int(self.actual_sms),
            "green_context_device": int(self.device_index),
            "green_context_full_device_sms": int(self.full_device_sms),
            "green_context_min_sm_partition_size": int(self.min_sm_partition_size),
            "green_context_sm_coscheduled_alignment": int(self.sm_coscheduled_alignment),
            "green_context_stream_handle": int(self.stream_handle),
            "rubin_model": (
                "requested 72 Blackwell SMs to approximate Rubin-like "
                "SMs-per-TB/s; actual SM count may be rounded by hardware"
            ),
        }


def create_green_context(*, requested_sms: int = 72, device_index: int = 0) -> GreenContext:
    """Create a CUDA green context stream with approximately requested_sms SMs.

    Requires cuda-python with CUDA 13.1 driver bindings and a sufficiently new
    NVIDIA driver.  The returned context must stay alive while its PyTorch
    ExternalStream is used.
    """
    if requested_sms <= 0:
        raise ValueError(f"requested_sms must be positive, got {requested_sms}")
    if cuda is None:
        raise RuntimeError(
            "cuda-python driver bindings are unavailable; install cuda-python>=13.1"
        )
    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is not available")

    torch.cuda.set_device(int(device_index))
    # Ensure the primary context exists before the green-context create call,
    # matching NVIDIA's guidance for lower setup overhead.
    torch.cuda._lazy_init()  # type: ignore[attr-defined]

    _check_cuda(cuda.cuInit(0), "cuInit")
    dev = _check_cuda(cuda.cuDeviceGet(int(device_index)), "cuDeviceGet")
    initial = _check_cuda(
        cuda.cuDeviceGetDevResource(
            dev, cuda.CUdevResourceType.CU_DEV_RESOURCE_TYPE_SM
        ),
        "cuDeviceGetDevResource(SM)",
    )
    full_sms = int(initial.sm.smCount)

    def _sm_resource_field(resource: Any, name: str, oversize_index: int) -> int:
        value = getattr(resource.sm, name, None)
        if value is not None:
            return int(value)
        # Some cuda-python builds expose only smCount as a typed attribute and keep
        # the rest of CUdevSmResource in the generated binding's private oversize
        # payload.  The first three uint32 entries are smCount,
        # minSmPartitionSize, and smCoscheduledAlignment.
        raw = getattr(resource, "_oversize", b"")
        offset = 4 * int(oversize_index)
        if isinstance(raw, (bytes, bytearray)) and len(raw) >= offset + 4:
            return int.from_bytes(raw[offset : offset + 4], byteorder="little", signed=False)
        return 0

    min_part = _sm_resource_field(initial, "minSmPartitionSize", 1)
    cosched_align = _sm_resource_field(initial, "smCoscheduledAlignment", 2)

    split_payload = _check_cuda(
        cuda.cuDevSmResourceSplitByCount(1, initial, 0, int(requested_sms)),
        "cuDevSmResourceSplitByCount",
    )
    if not isinstance(split_payload, tuple) or len(split_payload) < 1:
        raise RuntimeError(
            f"Unexpected cuDevSmResourceSplitByCount payload: {split_payload!r}"
        )
    resources = split_payload[0]
    if not resources:
        raise RuntimeError("cuDevSmResourceSplitByCount returned no SM resources")
    subset = resources[0]

    desc = _check_cuda(cuda.cuDevResourceGenerateDesc([subset], 1), "cuDevResourceGenerateDesc")

    # In this cuda-python/driver environment, flags=0 returned INVALID_VALUE;
    # CU_GREEN_CTX_DEFAULT_STREAM is accepted and matches the CUDA 13.1 binding.
    create_flags = int(cuda.CUgreenCtxCreate_flags.CU_GREEN_CTX_DEFAULT_STREAM)
    green_ctx = _check_cuda(cuda.cuGreenCtxCreate(desc, dev, create_flags), "cuGreenCtxCreate")

    stream_flags = int(cuda.CUstream_flags.CU_STREAM_NON_BLOCKING)
    cu_stream = _check_cuda(
        cuda.cuGreenCtxStreamCreate(green_ctx, stream_flags, 0),
        "cuGreenCtxStreamCreate",
    )

    # cuStreamGetDevResource exists in cuda-python 13.1 but is not exported by
    # the installed 580-era driver here. Query the green context instead.
    actual_res = _check_cuda(
        cuda.cuGreenCtxGetDevResource(
            green_ctx, cuda.CUdevResourceType.CU_DEV_RESOURCE_TYPE_SM
        ),
        "cuGreenCtxGetDevResource(SM)",
    )
    actual_sms = int(actual_res.sm.smCount)

    stream = torch.cuda.ExternalStream(int(cu_stream), device=int(device_index))
    ctx = GreenContext(
        requested_sms=int(requested_sms),
        actual_sms=actual_sms,
        device_index=int(device_index),
        full_device_sms=full_sms,
        min_sm_partition_size=min_part,
        sm_coscheduled_alignment=cosched_align,
        _green_ctx=green_ctx,
        _cu_stream=cu_stream,
        stream=stream,
    )
    atexit.register(ctx.close)
    return ctx


def make_green_context_from_args(args: Any) -> Optional[GreenContext]:
    """Create a green context from common benchmark args, if requested."""
    requested = int(getattr(args, "green_sms", 0) or 0)
    if bool(getattr(args, "rubin_green", False)) and requested <= 0:
        requested = 72
    if requested <= 0:
        return None
    device_index = int(getattr(args, "green_device", 0) or 0)
    return create_green_context(requested_sms=requested, device_index=device_index)


def add_green_context_args(parser: Any) -> None:
    parser.add_argument(
        "--green-sms",
        type=int,
        default=0,
        help="Run timed kernels on a CUDA green-context stream with this many requested SMs (0 disables).",
    )
    parser.add_argument(
        "--green-device",
        type=int,
        default=0,
        help="CUDA device index for --green-sms (default: 0).",
    )
    parser.add_argument(
        "--rubin-green",
        action="store_true",
        help="Alias for --green-sms 72, approximating Rubin SMs-per-TB/s on Blackwell.",
    )


def green_context_meta(ctx: Optional[GreenContext]) -> Dict[str, Any]:
    return {} if ctx is None else ctx.metadata()


def stream_scope(stream: Optional[torch.cuda.Stream]):
    return torch.cuda.stream(stream) if stream is not None else _NullContext()


class _NullContext:
    def __enter__(self):
        return None

    def __exit__(self, exc_type, exc, tb):
        return False


def synchronize_stream_dependencies(stream: Optional[torch.cuda.Stream], device: torch.device | int | None = None) -> None:
    """Synchronize default/current stream around work on an optional external stream."""
    if stream is None:
        return
    if device is None:
        device = stream.device
    current = torch.cuda.current_stream(device)
    stream.wait_stream(current)


def finish_stream_dependencies(stream: Optional[torch.cuda.Stream], device: torch.device | int | None = None) -> None:
    if stream is None:
        return
    if device is None:
        device = stream.device
    current = torch.cuda.current_stream(device)
    current.wait_stream(stream)
